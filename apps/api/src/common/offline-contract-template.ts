export const OFFLINE_CONTRACT_TEMPLATE_HASH = createHash('sha256')
  .update(JSON.stringify({ version: OFFLINE_CONTRACT_TEMPLATE_VERSION, pages }))
  .digest('hex');

const requiredKeys: (keyof OfflineContractBindings)[] = [
  'guardianFullName',
  'guardianRole',
  'studentFullName',
  'studentNationalId',
  'educationLevel',
  'grade',
  'academicYear',
  'serviceAmountRial',
  'serviceAmountToman',
  'serviceAmountTomanWords',
  'paymentState',
  'homeAddress',
  'postalCode',
  'homePhone',
  'schoolName',
  'serviceType',
  'contractStartDate',
  'decisionDeadline',
  'generatedDate',
];

export function safeContractValue(value: unknown, maxLength = 500): string {
  return [...String(value ?? '')]
    .filter((character) => {
      const code = character.charCodeAt(0);
      return character !== '<' && character !== '>' && code > 31 && code !== 127;
    })
    .join('')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, maxLength);
}

export function renderOfflineContract(bindings: OfflineContractBindings) {
  const missing = requiredKeys.filter((key) => !safeContractValue(bindings[key]));
  if (missing.length) {
    throw new ConflictError(
      'INCOMPLETE_CONTRACT_DATA',
      `اطلاعات الزامی قرارداد ناقص است: ${missing.join(', ')}`,
    );
  }
  const safe = Object.fromEntries(
    Object.entries(bindings).map(([key, value]) => [key, safeContractValue(value)]),
  );
  const renderedPages = pages.map((page) =>
    page.map((paragraph) =>
      paragraph.replace(/\{\{(\w+)\}\}/g, (_, key: string) => safe[key] ?? ''),
    ),
  );
  return {
    templateVersion: OFFLINE_CONTRACT_TEMPLATE_VERSION,
    templateHash: OFFLINE_CONTRACT_TEMPLATE_HASH,
    bindings: safe as OfflineContractBindings,
    pages: renderedPages,
  };
}
